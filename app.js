(function(){
  const KEY = "ali.consent";
  const box = document.getElementById("consent");
  if(!box) return;
  let saved = null;
  try{ saved = localStorage.getItem(KEY); }catch(e){}
  if(saved === "yes" || saved === "no") return;

  const q = document.getElementById("consentQ");
  const info = document.getElementById("consentInfo");
  const yes = document.getElementById("consentYes");
  const no = document.getElementById("consentNo");
  let step = 1;

  function render(){
    const d = I18N[currentLang()] || I18N.en;
    const qKey = step === 1 ? "consent.q" : "consent.q2";
    const noKey = step === 1 ? "consent.no" : "consent.nah_no";
    q.setAttribute("data-i18n", qKey);
    q.textContent = d[qKey];
    no.setAttribute("data-i18n", noKey);
    no.textContent = d[noKey];
    info.hidden = step !== 1;
  }

  function decide(v){
    try{ localStorage.setItem(KEY, v); }catch(e){}
    box.classList.add("out");
    setTimeout(()=>{ box.hidden = true; }, 500);
  }

  yes.addEventListener("click", ()=>decide("yes"));
  no.addEventListener("click", ()=>{
    if(step === 1){ step = 2; render(); }
    else decide("no");
  });

  render();
  setTimeout(()=>{ box.hidden = false; }, 1600);
})();
