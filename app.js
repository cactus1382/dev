const modal = document.getElementById("modal");
const modalBody = document.getElementById("modalBody");
let lastFocused = null;

function openModal(markup){
  lastFocused = document.activeElement;
  modalBody.innerHTML = markup;
  modal.hidden = false;
  document.body.style.overflow = "hidden";
  const first = modal.querySelector("button, input, textarea, select, [tabindex]");
  if(first) first.focus();
}
function closeModal(){
  if(modal.hidden) return;
  modal.classList.add("closing");
  setTimeout(()=>{
    modal.hidden = true;
    modal.classList.remove("closing");
    document.body.style.overflow = "";
    modalBody.innerHTML = "";
  }, 260);
  if(lastFocused && lastFocused.focus) lastFocused.focus();
}
modal.addEventListener("click", e=>{
  if(e.target.closest("[data-close]")) closeModal();
});
document.addEventListener("keydown", e=>{
  if(e.key === "Escape" && !modal.hidden) closeModal();
});

function openPopup(id){
  const lang = currentLang();
  const data = (POPUPS[lang] || POPUPS.en)[id];
  if(!data) return;
  const listHtml = data.list
    ? '<ul class="modal-list">' + data.list.map(li=>'<li><span>' + esc(li) + '</span></li>').join("") + '</ul>'
    : "";
  const imgHtml = data.img
    ? '<img class="modal-img" src="' + esc(data.img) + '" alt="' + esc(data.title) + '" />'
    : "";
  const metaHtml = data.meta
    ? '<div class="modal-foot"><span class="muted">' + esc(data.meta) + '</span></div>'
    : "";
  openModal(imgHtml + '<h3 id="modalTitle">' + esc(data.title) + '</h3><p>' + esc(data.body) + '</p>' + listHtml + metaHtml);
}
document.querySelectorAll("[data-popup]").forEach(el=>{
  el.addEventListener("click", e=>{
    if(e.target.closest("a,button")) return;
    openPopup(el.getAttribute("data-popup"));
  });
  el.addEventListener("keydown", e=>{
    if(e.key === "Enter" || e.key === " "){
      e.preventDefault();
      openPopup(el.getAttribute("data-popup"));
    }
  });
});

